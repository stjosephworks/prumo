// What the run changed, so a failure halfway puts the project back as it found it: each file it rewrote returns
// to what it held, and each it created goes.
class Journal {
  private readonly before = new Map<string, string | null>()

  async keep(path: string): Promise<void> {
    if (!this.before.has(path)) {
      this.before.set(path, existsSync(path) ? await readFile(path, 'utf8') : null)
    }
  }

  creates(path: string): void {
    if (!this.before.has(path)) {
      this.before.set(path, null)
    }
  }

  async undo(): Promise<void> {
    for (const [path, text] of [...this.before].reverse()) {
      if (text === null) {
        await rm(path, { recursive: true, force: true })
      } else {
        await writeFile(path, text)
      }
    }
  }
}

function envLine(text: string, key: string): string | undefined {
  return new RegExp(`^${key}=(.*)$`, 'm').exec(text)?.[1]?.trim()
}

function withEnvLine(text: string, key: string, value: string): string {
  return text.replace(new RegExp(`^${key}=.*$`, 'm'), `${key}=${value}`)
}

async function readEnv(directory: string): Promise<string> {
  for (const file of ['.env', '.env.example']) {
    const text = await readFile(join(directory, file), 'utf8').catch(() => undefined)

    if (text !== undefined) {
      return text
    }
  }

  return ''
}

const SCHEME_BLOCK = (scheme: string) =>
  `# The mobile app's scheme, as in app.json: where it is sent back after signing in with a provider.\nMOBILE_APP_SCHEME=${scheme}\n`

export type Added = {
  app: App
  directory: string
  port: number
  areas: string[]
  installed: boolean
}

export async function addApp({
  templates,
  knowledge,
  cwd,
  type,
  framework,
  name = type,
  install,
  childOutput = 'inherit',
}: {
  templates: string
  knowledge: string
  cwd: string
  type: AppType
  // A web app's; Vite when none is given.
  framework?: WebFramework
  name?: string
  install: boolean
  childOutput?: ChildOutput
}): Promise<Added> {
  const root = findProjectRoot(cwd)
  const config = readConfig(root)

  if (config.architecture !== 'monorepo') {
    throw new CliError(
      'not_a_workspace',
      'This project is one app, laid out alone. `prumo add` grows a workspace.',
    )
  }

  // The app is copied from this CLI's templates, so only the version that wrote the project gives it the
  // dependencies its catalog holds and an API that trusts several web apps.
  const wrote = config.prumo
  const running = cliVersion()

  if (wrote !== running) {
    const [major = 0, minor = 0] = (wrote ?? '0.0').split('.').map(Number)

    throw new CliError(
      'version_mismatch',
      major === 0 && minor < 6
        ? `This project was generated by Prumo ${wrote ?? 'before 0.1.1'}, and \`prumo add\` exists from 0.6.0.`
        : `This project was generated by Prumo ${wrote}, and this is ${running}. Run \`npx @stjoseph/prumo@${wrote} add ${framework === undefined ? type : `${type}:${framework}`} ${name}\`.`,
    )
  }

  const project = readJsonc<{ name: string }>(
    await readFile(join(root, 'package.json'), 'utf8'),
  ).name
  const apps = appsOf(config)
  const app: App = type === 'web' ? { name, type, framework: framework ?? 'vite' } : { name, type }
  const next = [...apps, app]

  validateApps(next, project)

  const directory = join(root, 'apps', name)

  if (existsSync(directory)) {
    throw new CliError('target_not_empty', `${relative(root, directory)} already exists.`)
  }

  const answers: Answers = { ...config, name: project, types: typesOf(next), apps: next }
  const journal = new Journal()
  const unwatch = watchInterrupt()

  try {
    const result = await write({ templates, knowledge, root, project, apps, app, answers, journal })

    if (install) {
      await journal.keep(join(root, 'pnpm-lock.yaml'))
      // The new app is a new importer in the lockfile, which pnpm under CI would otherwise refuse to write.
      run('pnpm', ['install', '--no-frozen-lockfile'], root, childOutput)
      // Only what this run wrote: the rest of the workspace is the team's, formatted as they left it.
      run(
        'pnpm',
        [
          'exec',
          'biome',
          'check',
          '--write',
          // Written with forward slashes, which every system takes and a Windows shell needs no quotes for.
          ...result.written.map((path) => relative(root, path).split(sep).join('/')),
        ],
        root,
        childOutput,
      )

      if (templateOf(app) === 'web-vite') {
        run('pnpm', ['exec', 'tsr', 'generate'], directory, childOutput)
      }
    }

    return { app, directory, port: result.port, areas: result.areas, installed: install }
  } catch (error: unknown) {
    await journal.undo()
    throw error
  } finally {
    unwatch()
  }
}

async function write({
  templates,
  knowledge,
  root,
  project,
  apps,
  app,
  answers,
  journal,
}: {
  templates: string
  knowledge: string
  root: string
  project: string
  apps: App[]
  app: App
  answers: Answers
  journal: Journal
}): Promise<{ port: number; areas: string[]; written: string[] }> {
  const at = (one: App) => join(root, 'apps', one.name)
  const directory = at(app)
  const written = [directory]
  const [api] = appsOfType(apps, 'api')
  const rewrite = async (path: string, change: (text: string) => string) => {
    await journal.keep(path)
    await writeFile(path, change(await readFile(path, 'utf8')))
  }

  journal.creates(directory)
  await copyApp(templates, root, app)
  await applyFeatures(directory, templateOf(app), enabledFor(answers))
  await applyLanguages(directory, answers.languages)

  // The first port of its template that no app of the workspace holds, as each one's .env says today.
  const { key, from, site } = PORTS[templateOf(app)]
  const held = new Set<number>()

  for (const other of apps) {
    const port = envLine(await readEnv(at(other)), PORTS[templateOf(other)].key)
    held.add(Number(port ?? PORTS[templateOf(other)].from))
  }

  let port = from

  while (held.has(port)) {
    port += 1
  }

  await rewrite(join(directory, '.env.example'), (text) => {
    const withPort = withEnvLine(text, key, String(port))

    return site === undefined ? withPort : withEnvLine(withPort, site, `http://localhost:${port}`)
  })

  if (templateOf(app) === 'web-next') {
    await rewrite(join(directory, 'package.json'), (text) => {
      const start = readJsonc<{ scripts: { start: string } }>(text).scripts.start

      return setJsonc(text, ['scripts', 'start'], start.replace(`--port ${from}`, `--port ${port}`))
    })
  }

  if (CLIENTS.includes(app.type)) {
    const contract = join(root, 'packages', 'api-contract')

    if (existsSync(contract)) {
      await joinContract(directory)
    } else {
      journal.creates(contract)
      await copyTemplate(join(templates, 'workspace', 'packages', 'api-contract'), contract)
      await extractContract(root, [app])
      written.push(contract)
    }
  }

  // The workspace's languages are its package's; a workspace whose apps spoke none yet gets the package now.
  if (existsSync(join(directory, 'src', 'i18n', 'locales.ts'))) {
    const i18n = join(root, 'packages', 'i18n')

    if (existsSync(i18n)) {
      await joinI18n(root, directory)
    } else {
      journal.creates(i18n)
      await copyTemplate(join(templates, 'workspace', 'packages', 'i18n'), i18n)
      await extractI18n(root, [app])
      written.push(i18n)
    }
  }

  // Before the app's own manifest becomes `catalog:`, which is what says the versions it needs.
  const manifest = readJsonc<Parameters<typeof collectCatalog>[0][number]>(
    await readFile(join(directory, 'package.json'), 'utf8'),
  )
  const workspaceYaml = join(root, 'pnpm-workspace.yaml')

  await rewrite(workspaceYaml, (text) => addToCatalogs(text, collectCatalog([manifest])))
  await adaptAppConfig(root, directory)

  const approvals = await takeBuildApprovals(directory)
  await rewrite(workspaceYaml, (text) => addApprovals(text, approvals))

  await rewrite(join(root, 'package.json'), (text) => {
    let pkg = setJsonc(text, ['scripts', app.name], `pnpm --filter ${app.name} dev`)

    if (app.type === 'api') {
      const dev = readJsonc<{ scripts: { dev: string } }>(pkg).scripts.dev
      pkg = setJsonc(pkg, ['scripts', 'dev'], `${rootDevPrefix(app.name)}${dev}`)
    }

    return pkg
  })

  await writeLocalEnv(directory, app.type)

  const origin = `http://localhost:${port}`
  const webs = appsOfType(apps, 'web')
  const mobile = appsOfType(apps, 'mobile')[0]

  for (const file of ['.env.example', '.env']) {
    // A new web app is one more origin for the API to trust.
    if (app.type === 'web' && api !== undefined && existsSync(join(at(api), file))) {
      await rewrite(join(at(api), file), (text) => {
        // An API with no web app yet names the template's first web port, which this one may not be on: the first
        // origin is where MCP consent opens, so the first web app replaces it rather than following it.
        const list =
          webs.length === 0
            ? []
            : (envLine(text, 'WEB_ORIGIN') ?? '').split(',').filter((entry) => entry !== '')

        return list.includes(origin)
          ? text
          : withEnvLine(text, 'WEB_ORIGIN', [...list, origin].join(','))
      })
    }

    // A new API trusts the web apps there already, on the ports they hold.
    if (app.type === 'api' && webs.length > 0) {
      const origins: string[] = []

      for (const web of webs) {
        const { key: webKey, from: webFrom } = PORTS[templateOf(web)]
        origins.push(`http://localhost:${envLine(await readEnv(at(web)), webKey) ?? webFrom}`)
      }

      await rewrite(join(directory, file), (text) =>
        withEnvLine(text, 'WEB_ORIGIN', origins.join(',')),
      )
    }

    // A mobile app signing in with a provider is sent back by its scheme, which the API was given none of.
    if (
      app.type === 'mobile' &&
      api !== undefined &&
      answers.social.length > 0 &&
      existsSync(join(at(api), file))
    ) {
      await rewrite(join(at(api), file), (text) =>
        /^MOBILE_APP_SCHEME=/m.test(text)
          ? text
          : text.replace(/^(WEB_ORIGIN=.*\n)/m, `$1${SCHEME_BLOCK(schemeFor(project))}`),
      )
    }
  }

  // A client points at the API where it answers now, which may not be where the template said.
  const apiUrl = api === undefined ? undefined : envLine(await readEnv(at(api)), 'API_URL')
  const clientKey = API_URL_KEYS[templateOf(app)]

  if (apiUrl !== undefined && clientKey !== undefined) {
    await rewrite(join(directory, '.env'), (text) => withEnvLine(text, clientKey, apiUrl))
  }

  if (app.type === 'api') {
    await nameCompose(directory, project)
    await settleMobileScheme(directory, mobile === undefined ? null : schemeFor(project))
  }

  if (app.type === 'mobile') {
    await nameMobileApp(directory, project)
  }

  const prumo = join(root, '.prumo')

  for (const area of areasFor(answers).filter((each) => !existsSync(join(prumo, each)))) {
    journal.creates(join(prumo, area))
  }

  await journal.keep(join(prumo, 'INDEX.md'))
  await journal.keep(join(prumo, 'config.json'))

  const areas = await growContext(knowledge, root, answers)

  return { port, areas, written: [...written, join(prumo, 'config.json')] }
}
